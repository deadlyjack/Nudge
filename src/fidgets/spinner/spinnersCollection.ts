function createSpinnerCollectionItem(
	id: SpinnerVariantId,
	assetIndex: number,
	name: string,
	type: SpinnerCollectionType,
	weight: number,
	friction: number,
	originOffset: SpinnerVisualOriginOffset,
	colorProfile: Omit<SpinnerColorOption, "id" | "label">,
): SpinnerCollectionItem {
	return {
		assetIndex,
		color: `linear-gradient(145deg, ${colorProfile.light}, ${colorProfile.accent} 52%, ${colorProfile.deep})`,
		colorProfile: {
			...colorProfile,
			id: `${id}-color`,
			label: `${name} color`,
		},
		friction,
		id,
		name,
		originOffset,
		type,
		weight,
	};
}
